export function getTouchlineClubHubCoachPanelCopy(locale: string, draftLocalesEnabled = false) {
  const resolved = resolveTouchlineCatalogueLocale(locale, draftLocalesEnabled);
  const title = resolveTouchlineCoachZoomPresentation(resolved, draftLocalesEnabled).copy.firstTeamCoach;
  return { title, ariaTitle: resolved === "pt-BR" ? "treinador principal" : resolved === "en-GB" ? "first-team coach" : title,
    staff: getTouchlineClubHubRosterCopy(resolved, draftLocalesEnabled).staff, description: coachDescriptions[resolved] };
}

