/** Local opt-in only; the site-wide core resolver remains closed. */
export function touchlineClubHubText(locale: string, key: TouchLineTranslationKey, draftLocalesEnabled = false) {
  const resolved = resolveTouchlineCatalogueLocale(locale, draftLocalesEnabled);
  return resolved === "en-GB" || resolved === "pt-BR"
    ? touchLineT(resolved, key) : touchlineCoreDrafts[resolved][key];
}

