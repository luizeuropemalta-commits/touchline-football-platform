/** Display-only count; never modifies saved category settings. */
export function formatTouchlineNotificationActiveCount(count: number, locale?: string | null, draftLocalesEnabled = false): string {
  if (!Number.isSafeInteger(count) || count < 0) return "—";
  const resolved = resolveTouchlineCatalogueLocale(locale, draftLocalesEnabled);
  const number = new Intl.NumberFormat(resolved).format(count);
  const plural = new Intl.PluralRules(resolved).select(count);
  if (resolved === "ar-SA") {
    if (plural === "one") return "فئة واحدة مفعّلة";
    if (plural === "two") return "فئتان مفعّلتان";
    return `${number} ${plural === "zero" || plural === "few" ? "فئات مفعّلة" : "فئة مفعّلة"}`;
  }
  const forms = {
    "en-GB": ["category active", "categories active"],
    "pt-BR": ["categoria ativa", "categorias ativas"],
    "es-ES": ["categoría activa", "categorías activas"],
    "it-IT": ["categoria attiva", "categorie attive"],
    "fr-FR": ["catégorie active", "catégories actives"],
    "tr-TR": ["etkin kategori", "etkin kategori"],
    "de-DE": ["aktive Kategorie", "aktive Kategorien"],
  } as const;
  return `${number} ${forms[resolved][plural === "one" ? 0 : 1]}`;
}
