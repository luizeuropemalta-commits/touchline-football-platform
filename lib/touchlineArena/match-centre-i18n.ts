const arabicPlurals = new Intl.PluralRules("ar-SA");
function arabicCount(count: number, one: string, two: string, few: string, many: string) {
  const category = arabicPlurals.select(count);
  if (category === "two") return two;
  return `${count} ${category === "zero" || category === "few" ? few : category === "many" ? many : one}`;
}

