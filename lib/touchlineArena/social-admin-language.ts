export function socialAdminError(error: unknown, locale: TouchLineAuthLocale, fallback: string) {
  const message = typeof error === "string" ? error : error instanceof Error ? error.message : "";
  return Object.hasOwn(apiErrors, message) ? locale === "pt-BR" ? apiErrors[message] : message : socialAdminLanguage(locale).t(fallback);
}
