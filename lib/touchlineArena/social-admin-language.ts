export function socialAdminDate(value: string | null | undefined, locale: TouchLineAuthLocale) {
  if (!value || !Number.isFinite(Date.parse(value))) return "—";
  return new Intl.DateTimeFormat(locale, { dateStyle: "short", timeStyle: "medium", timeZone: "Europe/Malta" }).format(new Date(value));
}

