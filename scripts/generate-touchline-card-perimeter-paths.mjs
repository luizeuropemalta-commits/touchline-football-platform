import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const sharp = createRequire(import.meta.url)("sharp");
const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const outputFile = join(repositoryRoot, "lib/touchlineArena/card-art-perimeter-paths.ts");
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: node scripts/generate-touchline-card-perimeter-paths.mjs [--check]");
}
const checkOnly = args[0] === "--check";
const tiers = ["ruby-red", "sapphire-blue", "amethyst-purple", "radiant-gold", "emerald-green", "clear-diamond", "diamond-gold"];
const coaches = ["02_red", "01_blue", "04_purple", "06_gold", "03_green", "05_silver", "07_golddiamond"];
const playerRoot = join(repositoryRoot, "public/touchlineArena/cards/templates/zoom/clubs");
const sources = [];
const paths = { player: {}, coach: {} };
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
const sourcePath = file => relative(repositoryRoot, file).split(sep).join("/");

function simplify(points) {
  if (points.length < 3) return points;
  const first = points[0], last = points.at(-1);
  let max = 0, index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i];
    const distance = Math.abs((last[1] - first[1]) * x - (last[0] - first[0]) * y
      + last[0] * first[1] - last[1] * first[0])
      / Math.max(1, Math.hypot(last[1] - first[1], last[0] - first[0]));
    if (distance > max) { max = distance; index = i; }
  }
  return max > 1.2
    ? [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))]
    : [first, last];
}

async function contour(file, width, height) {
  const input = readFileSync(file);
  sources.push({ path: sourcePath(file), sha256: sha256(input) });
  const { data, info } = await sharp(input).resize(width, height, { fit: "fill" })
    .ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const left = [], right = [];
  for (let y = 0; y < height; y += 2) {
    let first = -1, last = -1;
    for (let x = 0; x < width; x++) {
      if (data[(y * width + x) * info.channels + info.channels - 1] >= 200) {
        if (first < 0) first = x;
        last = x;
      }
    }
    if (first >= 0) { left.push([first + 1, y]); right.push([last - 1, y]); }
  }
  const points = [...simplify(left), ...simplify(right).reverse()];
  if (points.length < 3) throw new Error(`No usable alpha contour: ${sourcePath(file)}`);
  return `M${points.map(point => point.join(" ")).join("L")}Z`;
}

const clubs = readdirSync(playerRoot, { withFileTypes: true }).filter(entry => entry.isDirectory()).map(entry => entry.name).sort();
for (const club of clubs) {
  const directory = join(playerRoot, club, "market-tiers");
  const assets = readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith(".webp")).map(entry => entry.name).sort();
  if (!assets.length) throw new Error(`No player artwork: ${sourcePath(directory)}`);
  for (const asset of assets) {
    const key = `/touchlineArena/cards/templates/clubs/${club}/market-tiers/${asset.slice(0, -5)}`;
    paths.player[key] = await contour(join(directory, asset), 430, 691);
  }
}
if (!Object.keys(paths.player).length) throw new Error("No player artwork found");
for (let i = 0; i < tiers.length; i++) {
  paths.coach[tiers[i]] = await contour(join(repositoryRoot,
    `public/touchlineArena/cards/templates/zoom/coaches/${coaches[i]}_coach.webp`), 810, 1080);
}

// Share identical measured paths without sharing an assumed club silhouette.
const uniquePlayerContours = [...new Set(Object.values(paths.player))];
const contourIndex = new Map(uniquePlayerContours.map((path, index) => [path, index]));
const playerMap = Object.entries(paths.player).map(([key, path]) =>
  `    ${JSON.stringify(key)}: PLAYER_CARD_ART_PERIMETER_CONTOURS[${contourIndex.get(path)}]`).join(",\n");
const sourceManifest = sources.map(source => `// ${source.sha256}  ${source.path}`).join("\n");
const generatorHash = sha256(readFileSync(fileURLToPath(import.meta.url)));
const output = `// Generated by scripts/generate-touchline-card-perimeter-paths.mjs; do not edit.\n`
  + `// Verify without writing: node scripts/generate-touchline-card-perimeter-paths.mjs --check\n`
  + `// Measured from alpha >= 200 of each unchanged official zoom artwork.\n`
  + `// Outer row envelope, 2px sampling, <=1.2px simplification; 1px inward rail.\n`
  + `// Player coordinates 430x691; coach coordinates 810x1080.\n`
  + `// Player keys are decoded canonical club/tier paths without a size variant or extension.\n`
  + `// Generator SHA-256: ${generatorHash}\n`
  + `// Source SHA-256 manifest (${sources.length} assets):\n${sourceManifest}\n`
  + `const PLAYER_CARD_ART_PERIMETER_CONTOURS = ${JSON.stringify(uniquePlayerContours, null, 2)} as const;\n`
  + `export const CARD_ART_PERIMETER_PATHS = {\n  player: {\n${playerMap}\n  },\n`
  + `  coach: ${JSON.stringify(paths.coach, null, 2).replace(/\n/g, "\n  ")}\n} as const;\n\n`
  + `/** Resolve only a measured club asset; unknown or malformed input has no borrowed contour. */\n`
  + `export function resolvePlayerCardArtPerimeterPath(assetUrl: string | null | undefined): string | null {\n`
  + `  if (!assetUrl) return null;\n`
  + `  let path: string;\n`
  + `  try { path = decodeURIComponent(assetUrl.split(/[?#]/, 1)[0]); } catch { return null; }\n`
  + `  const canonical = path.replace(/\\.(?:png|webp)$/i, "")\n`
  + `    .replace(/^\\/touchlineArena\\/cards\\/templates\\/(?:zoom|live-compact|compact)\\/clubs\\//, "/touchlineArena/cards/templates/clubs/");\n`
  + `  return Object.hasOwn(CARD_ART_PERIMETER_PATHS.player, canonical)\n`
  + `    ? CARD_ART_PERIMETER_PATHS.player[canonical as keyof typeof CARD_ART_PERIMETER_PATHS.player] : null;\n`
  + `}\n`;

if (checkOnly) {
  let current;
  try { current = readFileSync(outputFile, "utf8"); } catch { /* Missing output is also a mismatch. */ }
  if (current !== output) {
    console.error("Card perimeter output differs from current sources. Run the generator without --check.");
    process.exitCode = 1;
  } else {
    console.info(`Card perimeter output verified: ${Object.keys(paths.player).length} player assets, ${uniquePlayerContours.length} unique player contours, ${tiers.length} coaches.`);
  }
} else {
  writeFileSync(outputFile, output);
  console.info(`Generated card perimeters: ${Object.keys(paths.player).length} player assets, ${uniquePlayerContours.length} unique player contours, ${tiers.length} coaches.`);
}
